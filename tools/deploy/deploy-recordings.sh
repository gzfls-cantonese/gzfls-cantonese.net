#!/usr/bin/env bash
# Package the recordings function (server/recordings) for deployment and emit its
# environment-variable manifest.
#
# PLATFORM-AGNOSTIC: this script makes NO cloud calls and pushes nothing. It
# produces a deployable zip + an env manifest + copy-paste deploy commands; the
# operator runs those against their FaaS/console of choice (Aliyun FC custom
# runtime, a container, an always-on host, ...).
#
# The function is a plain Node HTTP server (zero external deps, node: builtins
# only) that listens on $PORT, so it fits any "custom runtime / container that
# runs an HTTP server" target.
#
# Usage:
#   bash tools/deploy/deploy-recordings.sh [--dry-run] [--out DIR] [--function NAME]
#
#   --dry-run    print the full plan; create no files and make no cloud calls
#   --out DIR    artifact output dir (default: <repo>/dist-deploy/recordings)
#   --function   function/service name used in the artifacts and printed
#                commands (default: sanguo-recordings)
#   -h, --help   show help
#
# Env (reused from the site deploy; the function's OSS backend needs these):
#   required for the oss backend:
#     OSS_BUCKET  OSS_ENDPOINT  OSS_ACCESS_KEY_ID  OSS_ACCESS_KEY_SECRET
#   optional (documented defaults shown):
#     RECORDINGS_PREFIX(recordings)  RECORDINGS_MAX_DURATION(60)
#     RECORDINGS_PRESIGN_TTL(300)    PORT(8788)
#
# Secrets (OSS_ACCESS_KEY_ID / OSS_ACCESS_KEY_SECRET) are NEVER written to the
# manifest nor echoed; the manifest references them by name for the operator to
# set in the platform's secret store / function env. Use a RAM key scoped to
# put/delete on <RECORDINGS_PREFIX>/* only.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: bash tools/deploy/deploy-recordings.sh [--dry-run] [--out DIR] [--function NAME]

Packages the recordings function (server/recordings) for deployment. Platform-
agnostic: makes NO cloud calls and pushes nothing. Produces a deployable zip, an
env manifest, and copy-paste deploy commands for the operator to run.

  --dry-run    print the plan; create no files and make no cloud calls
  --out DIR    artifact dir (default: <repo>/dist-deploy/recordings)
  --function   function name used in artifacts/commands (default: sanguo-recordings)
  -h, --help   show this help

Env (reused from the site deploy):
  required for the oss backend: OSS_BUCKET OSS_ENDPOINT OSS_ACCESS_KEY_ID OSS_ACCESS_KEY_SECRET
  optional: RECORDINGS_PREFIX(recordings) RECORDINGS_MAX_DURATION(60) RECORDINGS_PRESIGN_TTL(300) PORT(8788)

Secrets are never written to disk or echoed.
EOF
}

DRY_RUN=0
OUT_DIR=""
FUNCTION_NAME="sanguo-recordings"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY_RUN=1; shift ;;
    --out) OUT_DIR="${2:?--out requires a value}"; shift 2 ;;
    --function) FUNCTION_NAME="${2:?--function requires a value}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; echo >&2; usage >&2; exit 2 ;;
  esac
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC="${ROOT}/server/recordings"
OUT_DIR="${OUT_DIR:-${ROOT}/dist-deploy/recordings}"
ZIP="${OUT_DIR}/${FUNCTION_NAME}.zip"
ENVF="${OUT_DIR}/${FUNCTION_NAME}.env"

[[ -d "${SRC}" ]] || { echo "missing function source: ${SRC}" >&2; exit 1; }
[[ -f "${SRC}/server.mjs" ]] || { echo "missing entry point: ${SRC}/server.mjs" >&2; exit 1; }

# Resolve the function environment. Non-secret values come from the current env
# with the function's documented defaults; secrets are referenced by name only.
PREFIX="${RECORDINGS_PREFIX:-recordings}"
MAXDUR="${RECORDINGS_MAX_DURATION:-60}"
TTL="${RECORDINGS_PRESIGN_TTL:-300}"
PORT="${PORT:-8788}"

have() { [[ -n "${!1:-}" ]]; }
mask() { if have "$1"; then echo "set (masked)"; else echo "MISSING"; fi; }
val()  { if have "$1"; then printf '%s' "${!1}"; else printf 'MISSING'; fi; }

# Files packaged into the zip: the function source, excluding tests and any
# local-only dirs. The function has zero external deps, so no node_modules.
zip_file_list() {
  ( cd "${SRC}" && find . -type f \
      -not -path './node_modules/*' \
      -not -name '*.test.mjs' \
      -not -path './.deploy/*' \
      -not -path './dist/*' \
      | sed 's|^\./||' | sort )
}

manifest() {
  cat <<EOF
# ${FUNCTION_NAME} environment — generated by tools/deploy/deploy-recordings.sh
# Set these as the function's environment variables on your platform.
# NON-secret values are filled from the build environment (or documented defaults).
# SECRET values are intentionally NOT written here — set them in your platform's
# secret store / function env before deploy. Never commit real keys.
OSS_BUCKET=${OSS_BUCKET:-__SET__}
OSS_ENDPOINT=${OSS_ENDPOINT:-__SET__}
OSS_ACCESS_KEY_ID=__SET_IN_SECRET_STORE__
OSS_ACCESS_KEY_SECRET=__SET_IN_SECRET_STORE__
RECORDINGS_PREFIX=${PREFIX}
RECORDINGS_MAX_DURATION=${MAXDUR}
RECORDINGS_PRESIGN_TTL=${TTL}
PORT=${PORT}
EOF
}

print_deploy_commands() {
  cat <<EOF
==> deploy (choose your platform; this script does NOT push for you)

  Aliyun FC 3.0 (custom runtime — runs an HTTP server on \$PORT):
    1) create/update function '${FUNCTION_NAME}': runtime custom (node>=18),
       start command 'node server.mjs', listening port ${PORT}
    2) upload code package: ${ZIP}
    3) set environment variables from: ${ENVF}
       (put OSS_ACCESS_KEY_ID / OSS_ACCESS_KEY_SECRET in the function env or a
        secret store; use a DEDICATED RAM key — not the site-deploy key — scoped
        to put/get/delete on '${PREFIX}/*' only, never list. See DEPLOY.md §9.1
        for the exact policy JSON.)
    4) attach an HTTP trigger and note its public URL
    5) build the site pointed at it:  VITE_RECORDINGS_API=<trigger-url>
       (see web/.env.example). Leaving it unset hides the whole recording UI —
       that is the rollback switch.

  Any container / always-on host:
    run the same env, exposing ${PORT}:   PORT=${PORT} node server.mjs

  After deploy, configure the OSS bucket (see server/recordings/README.md):
    - CORS: allow PUT from the site origin, AllowedHeader '*'
    - lifecycle: delete objects under '${PREFIX}/' after 7 days (orphan safety net)
    - RAM: scope the AccessKey to put/get/delete on '${PREFIX}/*' only (no list)
EOF
}

echo "==> recordings fn deploy plan"
echo "    function : ${FUNCTION_NAME}"
echo "    source   : ${SRC}"
echo "    artifacts: ${OUT_DIR}"
echo "    runtime  : node>=18 HTTP server, listens on PORT=${PORT}"
echo
echo "    environment (reused OSS_* + RECORDINGS_*):"
printf '      %-24s %s\n' OSS_BUCKET            "$(val OSS_BUCKET)"
printf '      %-24s %s\n' OSS_ENDPOINT          "$(val OSS_ENDPOINT)"
printf '      %-24s %s\n' OSS_ACCESS_KEY_ID     "$(mask OSS_ACCESS_KEY_ID)"
printf '      %-24s %s\n' OSS_ACCESS_KEY_SECRET "$(mask OSS_ACCESS_KEY_SECRET)"
printf '      %-24s %s\n' RECORDINGS_PREFIX     "${PREFIX}"
printf '      %-24s %s\n' RECORDINGS_MAX_DURATION "${MAXDUR}"
printf '      %-24s %s\n' RECORDINGS_PRESIGN_TTL  "${TTL}"
printf '      %-24s %s\n' PORT                  "${PORT}"
echo
echo "    zip contents (function source, tests excluded):"
zip_file_list | sed 's|^|      |'
echo

if [[ "${DRY_RUN}" == "1" ]]; then
  echo "    [dry-run] would create:"
  echo "      ${ZIP}"
  echo "      ${ENVF}"
  echo
  echo "    [dry-run] env manifest contents:"
  manifest | sed 's/^/      /'
  echo
  print_deploy_commands
  echo "==> dry-run complete: no files written, no cloud calls made."
  exit 0
fi

# Real run: package locally. Still no cloud calls — the operator deploys.
for v in OSS_BUCKET OSS_ENDPOINT OSS_ACCESS_KEY_ID OSS_ACCESS_KEY_SECRET; do
  have "$v" || echo "    warning: $v not set here; the manifest leaves it as a placeholder — set it on the platform before deploy." >&2
done

command -v zip >/dev/null 2>&1 || { echo "zip not found; install zip to package the function" >&2; exit 1; }

mkdir -p "${OUT_DIR}"
rm -f "${ZIP}"
echo "==> packaging -> ${ZIP}"
( cd "${SRC}" && zip -r -q "${ZIP}" . \
    -x 'node_modules/*' -x '*.test.mjs' -x '.deploy/*' -x 'dist/*' )

echo "==> writing env manifest -> ${ENVF}"
manifest > "${ENVF}"

if command -v sha256sum >/dev/null 2>&1; then
  SUM="$(sha256sum "${ZIP}" | cut -d' ' -f1)"
elif command -v shasum >/dev/null 2>&1; then
  SUM="$(shasum -a 256 "${ZIP}" | cut -d' ' -f1)"
else
  SUM="(no sha256 tool available)"
fi

echo
echo "==> packaged ${FUNCTION_NAME}"
echo "    zip    : ${ZIP}"
echo "    sha256 : ${SUM}"
echo "    env    : ${ENVF}  (secrets are placeholders — set them on the platform)"
echo
print_deploy_commands
